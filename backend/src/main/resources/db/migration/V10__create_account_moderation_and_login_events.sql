-- Story #38/#39: retain internal moderation reason and actor for an audit trail.
CREATE TABLE account_moderation_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES user_accounts(id) ON DELETE CASCADE,
    admin_id BIGINT NOT NULL REFERENCES user_accounts(id) ON DELETE CASCADE,
    action VARCHAR(16) NOT NULL CHECK (action IN ('SUSPEND', 'REACTIVATE')),
    reason VARCHAR(500),
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT account_moderation_reason_check CHECK (
        (action = 'SUSPEND' AND reason IS NOT NULL AND length(btrim(reason)) > 0)
        OR (action = 'REACTIVATE' AND reason IS NULL)
    )
);
CREATE INDEX account_moderation_account_time_idx
    ON account_moderation_events(account_id, occurred_at DESC, id DESC);

-- Story #41: record only login attempts attributable to existing accounts.
-- No credential, session token, device fingerprint or IP address is stored.
CREATE TABLE user_login_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES user_accounts(id) ON DELETE CASCADE,
    successful BOOLEAN NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX user_login_events_account_time_idx
    ON user_login_events(account_id, occurred_at DESC, id DESC);
