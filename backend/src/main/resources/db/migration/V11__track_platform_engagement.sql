-- Story #32: forward-only counts of successful user engagement operations.
-- The table intentionally stores no visitor IP, session ID, password or account identifier.
-- Historic events cannot be reconstructed from lifetime view totals or current favourites.
CREATE TABLE platform_engagement_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type VARCHAR(24) NOT NULL CHECK (event_type IN (
        'PROJECT_VIEW', 'FAVOURITE_ADDED', 'FAVOURITE_REMOVED')),
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX platform_engagement_type_time_idx
    ON platform_engagement_events (event_type, occurred_at);

-- Recorded at migration execution, NOT backdated to any earlier release.
CREATE TABLE platform_activity_tracking (
    metric VARCHAR(30) PRIMARY KEY,
    started_at TIMESTAMPTZ NOT NULL
);
INSERT INTO platform_activity_tracking(metric, started_at)
VALUES ('ENGAGEMENT', CURRENT_TIMESTAMP);
