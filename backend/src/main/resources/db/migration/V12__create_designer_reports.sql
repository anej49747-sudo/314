-- #43 customer reports, #42 User Admin resolution. Keep reports private.
CREATE TABLE designer_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES user_accounts(id) ON DELETE CASCADE,
    designer_id BIGINT NOT NULL REFERENCES user_accounts(id) ON DELETE CASCADE,
    reason VARCHAR(40) NOT NULL CHECK (reason IN (
        'MISLEADING_INFORMATION', 'INAPPROPRIATE_COMMUNICATION', 'SUSPICIOUS_CONDUCT', 'OTHER')),
    description VARCHAR(2000) NOT NULL CHECK (length(btrim(description)) BETWEEN 20 AND 2000),
    status VARCHAR(16) NOT NULL DEFAULT 'OPEN'
        CHECK (status IN ('OPEN', 'RESOLVED', 'DISMISSED')),
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    decided_by BIGINT REFERENCES user_accounts(id) ON DELETE SET NULL,
    decision_note VARCHAR(1000),
    decided_at TIMESTAMPTZ,
    CONSTRAINT designer_reports_outcome_consistency CHECK (
       (status = 'OPEN' AND decided_by IS NULL AND decision_note IS NULL AND decided_at IS NULL)
       OR (status IN ('RESOLVED', 'DISMISSED') AND decision_note IS NOT NULL
           AND length(btrim(decision_note)) BETWEEN 10 AND 1000 AND decided_at IS NOT NULL)
    )
);
-- A customer may file another report on the same designer only after the previous one is closed.
CREATE UNIQUE INDEX designer_reports_one_open_per_pair
    ON designer_reports(customer_id, designer_id) WHERE status = 'OPEN';
CREATE INDEX designer_reports_status_submitted_idx
    ON designer_reports(status, submitted_at DESC, id DESC);
CREATE INDEX designer_reports_customer_idx ON designer_reports(customer_id);
