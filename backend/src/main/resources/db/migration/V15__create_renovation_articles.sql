-- Stories #36/#8: Manager-published plain-text articles with one optional cover photo.
-- Opaque photo keys are stored here; bytes remain in the existing local image store.
CREATE TABLE renovation_articles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(120) NOT NULL,
    summary VARCHAR(240) NOT NULL,
    content VARCHAR(10000) NOT NULL,
    cover_storage_key VARCHAR(80) UNIQUE,
    cover_content_type VARCHAR(32),
    published_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT renovation_article_title_check CHECK (length(btrim(title)) BETWEEN 5 AND 120),
    CONSTRAINT renovation_article_summary_check CHECK (length(btrim(summary)) BETWEEN 20 AND 240),
    CONSTRAINT renovation_article_content_check CHECK (length(btrim(content)) BETWEEN 100 AND 10000),
    CONSTRAINT renovation_article_cover_check CHECK (
        (cover_storage_key IS NULL AND cover_content_type IS NULL)
        OR (cover_storage_key IS NOT NULL AND cover_content_type IN
            ('image/jpeg', 'image/png', 'image/webp'))
    )
);
CREATE INDEX renovation_articles_published_idx ON renovation_articles (published_at DESC, id DESC);
