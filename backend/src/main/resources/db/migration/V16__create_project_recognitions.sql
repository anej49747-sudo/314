-- Stories #34/#35: month-based featured projects and independently named designer awards.
-- Recognition rows disappear when their project or designer is permanently deleted.
CREATE TABLE project_of_month (
    feature_month VARCHAR(7) PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES interior_design_projects(id) ON DELETE CASCADE,
    selected_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT project_of_month_period_format CHECK (feature_month ~ '^[0-9]{4}-(0[1-9]|1[0-2])$')
);
CREATE INDEX project_of_month_project_idx ON project_of_month (project_id);

CREATE TABLE designer_awards (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    designer_id BIGINT NOT NULL REFERENCES user_accounts(id) ON DELETE CASCADE,
    awarded_by BIGINT REFERENCES user_accounts(id) ON DELETE SET NULL,
    title VARCHAR(70) NOT NULL,
    title_key VARCHAR(160) NOT NULL,
    awarded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT designer_awards_title_length CHECK (length(btrim(title)) BETWEEN 3 AND 70),
    CONSTRAINT designer_awards_title_key_unique UNIQUE (designer_id, title_key)
);
CREATE INDEX designer_awards_designer_idx ON designer_awards (designer_id, awarded_at DESC, id DESC);
