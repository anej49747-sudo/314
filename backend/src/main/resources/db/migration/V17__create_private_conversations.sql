-- Sprint 4 (#25 / #47): one private customer/designer thread per account pair.
-- Removal of either account permanently removes the private conversation and messages.
CREATE TABLE private_conversations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES user_accounts(id) ON DELETE CASCADE,
    designer_id BIGINT NOT NULL REFERENCES user_accounts(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_message_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT private_conversations_pair_uq UNIQUE (customer_id, designer_id),
    CONSTRAINT private_conversations_distinct_accounts_ck CHECK (customer_id <> designer_id)
);
CREATE INDEX private_conversations_customer_recent_idx
    ON private_conversations (customer_id, last_message_at DESC, id DESC);
CREATE INDEX private_conversations_designer_recent_idx
    ON private_conversations (designer_id, last_message_at DESC, id DESC);

CREATE TABLE private_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL REFERENCES private_conversations(id) ON DELETE CASCADE,
    sender_id BIGINT NOT NULL REFERENCES user_accounts(id) ON DELETE CASCADE,
    body VARCHAR(2000) NOT NULL
        CHECK (length(btrim(body)) BETWEEN 1 AND 2000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX private_messages_conversation_recent_idx
    ON private_messages (conversation_id, id DESC);
