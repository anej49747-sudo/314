-- Sprint 4 #48/#49/#50: private pending questions become public only after a designer answer.
-- Deleting a project or the submitting customer removes its associated questions.
CREATE TABLE project_questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES interior_design_projects(id) ON DELETE CASCADE,
    customer_id BIGINT NOT NULL REFERENCES user_accounts(id) ON DELETE CASCADE,
    question VARCHAR(600) NOT NULL CHECK (length(btrim(question)) BETWEEN 10 AND 600),
    answer VARCHAR(2000) CHECK (answer IS NULL OR length(btrim(answer)) BETWEEN 1 AND 2000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    answered_at TIMESTAMPTZ,
    CONSTRAINT project_questions_answer_state_ck CHECK (
        (answer IS NULL AND answered_at IS NULL) OR (answer IS NOT NULL AND answered_at IS NOT NULL)
    )
);
CREATE INDEX project_questions_public_recent_idx
    ON project_questions (project_id, answered_at DESC, id DESC) WHERE answered_at IS NOT NULL;
CREATE INDEX project_questions_customer_pending_idx
    ON project_questions (customer_id, project_id, created_at DESC) WHERE answered_at IS NULL;
CREATE INDEX project_questions_project_pending_idx
    ON project_questions (project_id, created_at ASC, id ASC) WHERE answered_at IS NULL;
