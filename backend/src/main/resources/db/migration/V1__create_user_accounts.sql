-- First application schema migration. Run automatically by Flyway at backend startup.
CREATE TABLE user_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    salutation VARCHAR(8),
    name VARCHAR(160) NOT NULL,
    email VARCHAR(254) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(32) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT user_accounts_salutation_check CHECK (
        salutation IS NULL OR salutation IN ('MR', 'MRS', 'MS', 'MDM', 'MX', 'DR', 'PROF')
    ),
    CONSTRAINT user_accounts_role_check CHECK (
        role IN ('CUSTOMER', 'INTERIOR_DESIGNER', 'USER_ADMIN', 'PLATFORM_MANAGER')
    ),
    CONSTRAINT user_accounts_nonblank_name_check CHECK (length(btrim(name)) > 0),
    CONSTRAINT user_accounts_nonblank_email_check CHECK (length(btrim(email)) > 0)
);

-- A database constraint is required as an application pre-check alone is race-prone.
CREATE UNIQUE INDEX user_accounts_email_case_insensitive_uq ON user_accounts (lower(email));
