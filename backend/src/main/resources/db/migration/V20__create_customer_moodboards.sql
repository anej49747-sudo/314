-- Story #28: private, versioned freeform moodboards.
-- Existing photo bytes remain in the project's filesystem storage; do not copy them.
CREATE TABLE customer_moodboards (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES user_accounts(id) ON DELETE CASCADE,
    title VARCHAR(120) NOT NULL CHECK (length(btrim(title)) BETWEEN 1 AND 120),
    background_color CHAR(7) NOT NULL DEFAULT '#FFFFFF' CHECK (background_color ~ '^#[0-9a-fA-F]{6}$'),
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX customer_moodboards_owner_recent_idx
    ON customer_moodboards (customer_id, updated_at DESC, id DESC);

CREATE TABLE customer_moodboard_elements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    board_id BIGINT NOT NULL REFERENCES customer_moodboards(id) ON DELETE CASCADE,
    kind VARCHAR(12) NOT NULL CHECK (kind IN ('PHOTO', 'TEXT', 'SWATCH')),
    photo_id BIGINT REFERENCES project_images(id) ON DELETE SET NULL,
    source_label VARCHAR(180),
    text_content VARCHAR(180),
    color CHAR(7) CHECK (color IS NULL OR color ~ '^#[0-9a-fA-F]{6}$'),
    font_size INTEGER CHECK (font_size IS NULL OR font_size BETWEEN 12 AND 56),
    x INTEGER NOT NULL CHECK (x BETWEEN 0 AND 900),
    y INTEGER NOT NULL CHECK (y BETWEEN 0 AND 580),
    width INTEGER NOT NULL CHECK (width BETWEEN 55 AND 900),
    height INTEGER NOT NULL CHECK (height BETWEEN 45 AND 580),
    layer_order INTEGER NOT NULL CHECK (layer_order BETWEEN 0 AND 59),
    CONSTRAINT moodboard_elements_inside_canvas_ck CHECK (x + width <= 900 AND y + height <= 580)
);
CREATE INDEX customer_moodboard_elements_board_idx
    ON customer_moodboard_elements (board_id, layer_order);
