-- Story #26: Customer-owned, measured 2D renovation drafts.
-- All geometry is stored in centimetres (integer); each draft has a version for safe edits.
CREATE TABLE customer_design_drafts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES user_accounts(id) ON DELETE CASCADE,
    title VARCHAR(120) NOT NULL CHECK (length(btrim(title)) BETWEEN 1 AND 120),
    floor_width_cm INTEGER NOT NULL CHECK (floor_width_cm BETWEEN 400 AND 2500),
    floor_height_cm INTEGER NOT NULL CHECK (floor_height_cm BETWEEN 400 AND 2500),
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX customer_design_drafts_owner_recent_idx
    ON customer_design_drafts (customer_id, updated_at DESC, id DESC);

CREATE TABLE customer_design_elements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    draft_id BIGINT NOT NULL REFERENCES customer_design_drafts(id) ON DELETE CASCADE,
    kind VARCHAR(12) NOT NULL CHECK (kind IN ('ROOM', 'FURNITURE', 'OPENING')),
    name VARCHAR(80) NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 80),
    x_cm INTEGER NOT NULL CHECK (x_cm >= 0),
    y_cm INTEGER NOT NULL CHECK (y_cm >= 0),
    width_cm INTEGER NOT NULL CHECK (width_cm >= 20),
    height_cm INTEGER NOT NULL CHECK (height_cm >= 20),
    rotation_deg INTEGER NOT NULL DEFAULT 0 CHECK (rotation_deg >= 0 AND rotation_deg < 360),
    display_order INTEGER NOT NULL CHECK (display_order BETWEEN 0 AND 119)
);
CREATE INDEX customer_design_elements_draft_order_idx
    ON customer_design_elements (draft_id, display_order);
