-- Story #29: flat, named project categories. The database enforces uniqueness
-- even when two managers submit the same name at the same time.
CREATE TABLE project_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT project_categories_name_nonblank CHECK (length(btrim(name)) > 0)
);

CREATE UNIQUE INDEX project_categories_name_ci_uq ON project_categories (lower(btrim(name)));
