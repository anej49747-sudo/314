-- Story #113: shared project model for listing designer portfolios.
-- Later stories will add project creation/editing/deletion and image storage.
CREATE TABLE interior_design_projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    designer_id BIGINT NOT NULL REFERENCES user_accounts(id) ON DELETE CASCADE,
    category_id BIGINT NOT NULL REFERENCES project_categories(id),
    title VARCHAR(160) NOT NULL,
    description VARCHAR(3000) NOT NULL,
    status VARCHAR(16) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT interior_design_projects_title_nonblank CHECK (length(btrim(title)) > 0),
    CONSTRAINT interior_design_projects_description_nonblank CHECK (length(btrim(description)) > 0),
    CONSTRAINT interior_design_projects_status_check CHECK (status IN ('CURRENT', 'COMPLETED'))
);

CREATE INDEX interior_design_projects_designer_created_idx
    ON interior_design_projects (designer_id, created_at DESC, id DESC);
