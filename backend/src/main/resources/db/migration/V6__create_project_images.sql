-- Story #16: optional project photos are stored outside PostgreSQL; only metadata is retained.
CREATE TABLE project_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES interior_design_projects(id) ON DELETE CASCADE,
    storage_key VARCHAR(80) NOT NULL UNIQUE,
    content_type VARCHAR(32) NOT NULL,
    size_bytes BIGINT NOT NULL,
    display_order INTEGER NOT NULL,
    CONSTRAINT project_images_size_positive CHECK (size_bytes > 0),
    CONSTRAINT project_images_order_nonnegative CHECK (display_order >= 0),
    CONSTRAINT project_images_type_check CHECK (content_type IN ('image/jpeg', 'image/png', 'image/webp')),
    CONSTRAINT project_images_project_order_unique UNIQUE (project_id, display_order)
);
CREATE INDEX project_images_project_idx ON project_images (project_id);
