-- Story #22: a customer's current saved projects, with database-level duplicate prevention.
-- An individual save is not a historical view or shortlist event (Story #17 will define metrics).
CREATE TABLE customer_project_favourites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES user_accounts(id) ON DELETE CASCADE,
    project_id BIGINT NOT NULL REFERENCES interior_design_projects(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT customer_project_favourites_customer_project_uq UNIQUE (customer_id, project_id)
);

CREATE INDEX customer_project_favourites_project_idx ON customer_project_favourites (project_id);
