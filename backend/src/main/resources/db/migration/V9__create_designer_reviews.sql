-- Story #46: customer reviews of active interior designers.
-- Multiple reviews by the same customer are permitted; public display is Story #10.
CREATE TABLE designer_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    designer_id BIGINT NOT NULL REFERENCES user_accounts(id) ON DELETE CASCADE,
    customer_id BIGINT NOT NULL REFERENCES user_accounts(id) ON DELETE CASCADE,
    rating INTEGER NOT NULL,
    comment VARCHAR(2000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT designer_reviews_rating_range CHECK (rating BETWEEN 1 AND 5)
);

CREATE INDEX designer_reviews_designer_created_idx
    ON designer_reviews (designer_id, created_at DESC, id DESC);
